package com.faceswap.studio.engine

import com.faceswap.core.Tensor
import com.faceswap.core.TensorWire
import okhttp3.MediaType.Companion.toMediaType
import okhttp3.MultipartBody
import okhttp3.OkHttpClient
import okhttp3.Request
import okhttp3.RequestBody.Companion.toRequestBody
import okhttp3.ResponseBody
import org.json.JSONArray
import org.json.JSONObject
import java.io.ByteArrayOutputStream
import java.io.IOException
import java.security.SecureRandom
import java.security.cert.X509Certificate
import java.util.concurrent.TimeUnit
import javax.net.ssl.SSLContext
import javax.net.ssl.X509TrustManager

/** One model as advertised by the server's `/v1/health` manifest. */
data class ServerModelInfo(val id: String, val role: String, val inputs: List<String>, val outputs: List<String>)

/** One backend as advertised by the server's `/v1/diffusion/health` (see server/diffusion_app/main.py). */
data class DiffusionModelInfo(val id: String, val displayName: String, val role: String, val license: String, val notes: String)

/** Optional knobs for [RemoteClient.diffusionSwap] – all null = backend defaults (see server's SwapParams). */
data class DiffusionSwapParams(val steps: Int? = null, val guidanceScale: Float? = null, val identityStrength: Float? = null, val seed: Long? = null)

/** Server identity + device summary + the full model manifest, as returned by `/v1/health`. */
data class ServerInfo(val name: String, val version: String, val device: String, val models: List<ServerModelInfo>)

/** Connection target. Equatable so [EngineHolder] can tell when the active server changed and rebuild. */
data class ServerEndpoint(val host: String, val port: Int, val tls: Boolean, val apiKey: String) {
    val baseUrl get() = "${if (tls) "https" else "http"}://$host:$port"
    val valid get() = host.isNotBlank() && port in 1..65535
}

private val OCTET_STREAM = "application/octet-stream".toMediaType()

/**
 * A TLS trust manager that accepts the server's certificate without CA validation, for the common case of a
 * self-signed cert generated by `setup_server.sh` on a server the user controls directly (connecting by raw IP, not
 * a domain a public CA would issue for). Equivalent in spirit to pinning "whatever cert the box I just set up
 * presents" – acceptable because the user typed in the IP themselves, not because the network path is assumed safe.
 * Prefer a real certificate (e.g. via `--domain` + Let's Encrypt, see server/README.md) when the server has one.
 *
 * NOT used for a Cloudflare Tunnel address (`*.trycloudflare.com`, or any other public hostname): Cloudflare's edge
 * terminates real, publicly-trusted TLS for those, so [RemoteClient] validates that connection normally instead of
 * bypassing trust – see [looksLikeSelfSignedTarget].
 */
private object TrustAnyCert : X509TrustManager {
    override fun checkClientTrusted(chain: Array<out X509Certificate>?, authType: String?) = Unit
    override fun checkServerTrusted(chain: Array<out X509Certificate>?, authType: String?) = Unit
    override fun getAcceptedIssuers(): Array<X509Certificate> = emptyArray()
}

private val IPV4_LITERAL = Regex("""^\d{1,3}(\.\d{1,3}){3}$""")

/**
 * True for a bare LAN IP or a `.local`/`localhost` address – the cases `setup_server.sh` only ever has a
 * self-signed cert for, since no public CA will issue a certificate for an IP literal or a private hostname.
 * False for anything else, including a Cloudflare Tunnel's `*.trycloudflare.com` hostname or a `--domain` the
 * operator pointed Let's Encrypt at – both present a real, CA-issued certificate that should be validated
 * normally rather than trusted unconditionally.
 */
private fun looksLikeSelfSignedTarget(host: String): Boolean =
    host == "localhost" || host.endsWith(".local") || IPV4_LITERAL.matches(host) || host.contains(':') // IPv6 literal

/** Thin HTTP client for the custom inference backend. One instance per connected [ServerEndpoint]. */
class RemoteClient(private val endpoint: ServerEndpoint) {
    private val http: OkHttpClient = OkHttpClient.Builder()
        .connectTimeout(8, TimeUnit.SECONDS)
        // 300s, not the old 90s: a diffusion backend's first request (see diffusionSwap) can spend a minute or
        // more just loading a multi-GB pipeline onto the GPU before it even starts denoising; ordinary tensor
        // infer() calls finish in well under this either way, so raising it costs them nothing.
        .readTimeout(300, TimeUnit.SECONDS)
        .writeTimeout(300, TimeUnit.SECONDS)
        .retryOnConnectionFailure(true)
        .apply {
            if (endpoint.tls && looksLikeSelfSignedTarget(endpoint.host)) {
                val sslContext = SSLContext.getInstance("TLS").apply { init(null, arrayOf(TrustAnyCert), SecureRandom()) }
                sslSocketFactory(sslContext.socketFactory, TrustAnyCert)
                hostnameVerifier { _, _ -> true }
            }
            // Else: a public hostname (Cloudflare Tunnel, a --domain host) – use OkHttp's default system trust
            // store, which correctly validates the real certificate Cloudflare's edge (or Let's Encrypt) presents.
        }
        .build()

    private fun req(path: String): Request.Builder = Request.Builder().url(endpoint.baseUrl + path).apply {
        if (endpoint.apiKey.isNotBlank()) header("Authorization", "Bearer ${endpoint.apiKey}")
    }

    /** GET /v1/health – server identity, device summary, and the model manifest (ids, roles, input/output names). */
    fun fetchServerInfo(): ServerInfo {
        http.newCall(req("/v1/health").get().build()).execute().use { r ->
            if (!r.isSuccessful) throw IOException("Server returned HTTP ${r.code}" + (errorMessage(r.body)?.let { ": $it" } ?: ""))
            val j = JSONObject(r.body?.string() ?: "{}")
            val modelsArr = j.optJSONArray("models") ?: JSONArray()
            val models = (0 until modelsArr.length()).map { i ->
                val m = modelsArr.getJSONObject(i)
                ServerModelInfo(
                    id = m.getString("id"),
                    role = m.optString("role", "other"),
                    inputs = m.optJSONArray("inputs")?.let { a -> (0 until a.length()).map(a::getString) } ?: emptyList(),
                    outputs = m.optJSONArray("outputs")?.let { a -> (0 until a.length()).map(a::getString) } ?: emptyList(),
                )
            }
            return ServerInfo(
                name = j.optString("name", "faceswap-server"),
                version = j.optString("version", "?"),
                device = j.optString("device", "unknown device"),
                models = models,
            )
        }
    }

    /** Blocking RPC: runs model [modelId] on the server with [inputs], returns its named outputs. */
    fun infer(modelId: String, inputs: Map<String, Tensor>): Map<String, Tensor> {
        val body = ByteArrayOutputStream().apply { TensorWire.writeMap(this, inputs) }.toByteArray().toRequestBody(OCTET_STREAM)
        http.newCall(req("/v1/infer/$modelId").post(body).build()).execute().use { r ->
            if (!r.isSuccessful) throw IOException("$modelId: " + (errorMessage(r.body) ?: "server returned HTTP ${r.code}"))
            val stream = r.body?.byteStream() ?: throw IOException("$modelId: empty response from server")
            return TensorWire.readMap(stream)
        }
    }

    /**
     * GET /v1/diffusion/health – best-effort: returns an empty list (never throws) when the box has no diffusion
     * tier installed at all, since that's an entirely optional add-on (see server/setup_diffusion.sh) and most of
     * [RemoteCatalog.connect]'s callers shouldn't have to special-case "server reachable but diffusion absent"
     * differently from "no diffusion models configured".
     */
    fun fetchDiffusionInfo(): List<DiffusionModelInfo> = runCatching {
        http.newCall(req("/v1/diffusion/health").get().build()).execute().use { r ->
            if (!r.isSuccessful) return@use emptyList()
            val j = JSONObject(r.body?.string() ?: "{}")
            val arr = j.optJSONArray("models") ?: JSONArray()
            (0 until arr.length()).map { i ->
                val m = arr.getJSONObject(i)
                DiffusionModelInfo(
                    id = m.getString("id"),
                    displayName = m.optString("display_name", m.getString("id")),
                    role = m.optString("role", "swapper"),
                    license = m.optString("license", ""),
                    notes = m.optString("notes", ""),
                )
            }
        }
    }.getOrDefault(emptyList())

    /**
     * POST /v1/diffusion/swap/{modelId} – [sourcePng]/[targetPng] are whole encoded images (PNG/JPEG bytes, not
     * tensors – see diffusion_app/main.py's module docstring for why this is a different wire shape from [infer]).
     * Returns the swapped image's PNG bytes, already composited full-size by the server.
     */
    fun diffusionSwap(modelId: String, sourcePng: ByteArray, targetPng: ByteArray, params: DiffusionSwapParams = DiffusionSwapParams()): ByteArray {
        val body = MultipartBody.Builder().setType(MultipartBody.FORM)
            .addFormDataPart("source", "source.png", sourcePng.toRequestBody("image/png".toMediaType()))
            .addFormDataPart("target", "target.png", targetPng.toRequestBody("image/png".toMediaType()))
            .apply {
                params.steps?.let { addFormDataPart("steps", it.toString()) }
                params.guidanceScale?.let { addFormDataPart("guidance_scale", it.toString()) }
                params.identityStrength?.let { addFormDataPart("identity_strength", it.toString()) }
                params.seed?.let { addFormDataPart("seed", it.toString()) }
            }.build()
        http.newCall(req("/v1/diffusion/swap/$modelId").post(body).build()).execute().use { r ->
            if (!r.isSuccessful) throw IOException("$modelId: " + (errorMessage(r.body) ?: "server returned HTTP ${r.code}"))
            return r.body?.bytes() ?: throw IOException("$modelId: empty response from server")
        }
    }

    private fun errorMessage(body: ResponseBody?): String? = runCatching {
        JSONObject(body?.string() ?: return null).optString("error").takeIf { it.isNotBlank() }
    }.getOrNull()

    fun close() {
        http.dispatcher.executorService.shutdown()
        http.connectionPool.evictAll()
    }
}
