package com.faceswap.studio.engine

import com.faceswap.core.Tensor
import com.faceswap.core.TensorWire
import okhttp3.MediaType.Companion.toMediaType
import okhttp3.OkHttpClient
import okhttp3.Request
import okhttp3.RequestBody.Companion.toRequestBody
import okhttp3.ResponseBody
import org.json.JSONArray
import org.json.JSONObject
import java.io.ByteArrayOutputStream
import java.io.IOException
import java.security.SecureRandom
import java.security.cert.X509Certificate
import java.util.concurrent.TimeUnit
import javax.net.ssl.SSLContext
import javax.net.ssl.X509TrustManager

/** One model as advertised by the server's `/v1/health` manifest. */
data class ServerModelInfo(val id: String, val role: String, val inputs: List<String>, val outputs: List<String>)

/** Server identity + device summary + the full model manifest, as returned by `/v1/health`. */
data class ServerInfo(val name: String, val version: String, val device: String, val models: List<ServerModelInfo>)

/** Connection target. Equatable so [EngineHolder] can tell when the active server changed and rebuild. */
data class ServerEndpoint(val host: String, val port: Int, val tls: Boolean, val apiKey: String) {
    val baseUrl get() = "${if (tls) "https" else "http"}://$host:$port"
    val valid get() = host.isNotBlank() && port in 1..65535
}

private val OCTET_STREAM = "application/octet-stream".toMediaType()

/**
 * A TLS trust manager that accepts the server's certificate without CA validation, for the common case of a
 * self-signed cert generated by `setup_server.sh` on a server the user controls directly (connecting by raw IP, not
 * a domain a public CA would issue for). Equivalent in spirit to pinning "whatever cert the box I just set up
 * presents" – acceptable because the user typed in the IP themselves, not because the network path is assumed safe.
 * Prefer a real certificate (e.g. via `--domain` + Let's Encrypt, see server/README.md) when the server has one.
 */
private object TrustAnyCert : X509TrustManager {
    override fun checkClientTrusted(chain: Array<out X509Certificate>?, authType: String?) = Unit
    override fun checkServerTrusted(chain: Array<out X509Certificate>?, authType: String?) = Unit
    override fun getAcceptedIssuers(): Array<X509Certificate> = emptyArray()
}

/** Thin HTTP client for the custom inference backend. One instance per connected [ServerEndpoint]. */
class RemoteClient(private val endpoint: ServerEndpoint) {
    private val http: OkHttpClient = OkHttpClient.Builder()
        .connectTimeout(8, TimeUnit.SECONDS)
        .readTimeout(90, TimeUnit.SECONDS)
        .writeTimeout(90, TimeUnit.SECONDS)
        .retryOnConnectionFailure(true)
        .apply {
            if (endpoint.tls) {
                val sslContext = SSLContext.getInstance("TLS").apply { init(null, arrayOf(TrustAnyCert), SecureRandom()) }
                sslSocketFactory(sslContext.socketFactory, TrustAnyCert)
                hostnameVerifier { _, _ -> true }
            }
        }
        .build()

    private fun req(path: String): Request.Builder = Request.Builder().url(endpoint.baseUrl + path).apply {
        if (endpoint.apiKey.isNotBlank()) header("Authorization", "Bearer ${endpoint.apiKey}")
    }

    /** GET /v1/health – server identity, device summary, and the model manifest (ids, roles, input/output names). */
    fun fetchServerInfo(): ServerInfo {
        http.newCall(req("/v1/health").get().build()).execute().use { r ->
            if (!r.isSuccessful) throw IOException("Server returned HTTP ${r.code}" + (errorMessage(r.body)?.let { ": $it" } ?: ""))
            val j = JSONObject(r.body?.string() ?: "{}")
            val modelsArr = j.optJSONArray("models") ?: JSONArray()
            val models = (0 until modelsArr.length()).map { i ->
                val m = modelsArr.getJSONObject(i)
                ServerModelInfo(
                    id = m.getString("id"),
                    role = m.optString("role", "other"),
                    inputs = m.optJSONArray("inputs")?.let { a -> (0 until a.length()).map(a::getString) } ?: emptyList(),
                    outputs = m.optJSONArray("outputs")?.let { a -> (0 until a.length()).map(a::getString) } ?: emptyList(),
                )
            }
            return ServerInfo(
                name = j.optString("name", "faceswap-server"),
                version = j.optString("version", "?"),
                device = j.optString("device", "unknown device"),
                models = models,
            )
        }
    }

    /** Blocking RPC: runs model [modelId] on the server with [inputs], returns its named outputs. */
    fun infer(modelId: String, inputs: Map<String, Tensor>): Map<String, Tensor> {
        val body = ByteArrayOutputStream().apply { TensorWire.writeMap(this, inputs) }.toByteArray().toRequestBody(OCTET_STREAM)
        http.newCall(req("/v1/infer/$modelId").post(body).build()).execute().use { r ->
            if (!r.isSuccessful) throw IOException("$modelId: " + (errorMessage(r.body) ?: "server returned HTTP ${r.code}"))
            val stream = r.body?.byteStream() ?: throw IOException("$modelId: empty response from server")
            return TensorWire.readMap(stream)
        }
    }

    private fun errorMessage(body: ResponseBody?): String? = runCatching {
        JSONObject(body?.string() ?: return null).optString("error").takeIf { it.isNotBlank() }
    }.getOrNull()

    fun close() {
        http.dispatcher.executorService.shutdown()
        http.connectionPool.evictAll()
    }
}
