"""
Runtime configuration for the inference server, loaded from server_config.yaml. That file is normally generated by
setup/plan.py (invoked by setup_server.sh) from detected hardware — see setup/detect_hardware.py — but it's a plain
YAML file you can hand-edit or write yourself if you'd rather configure the box by hand.
"""
from __future__ import annotations

import dataclasses
import os
from pathlib import Path
from typing import List, Optional

import yaml

DEFAULT_CONFIG_PATH = Path(os.environ.get("FSW_SERVER_CONFIG", "server_config.yaml"))


@dataclasses.dataclass
class DeviceConfig:
    """One inference device: a CUDA GPU, or the special index -1 for CPU-only fallback."""
    index: int  # CUDA device ordinal, or -1 for CPU
    name: str  # e.g. "NVIDIA H100 80GB HBM3"
    tier: str  # hopper | ampere_datacenter | ada_datacenter | ampere_workstation | ada_consumer | older | cpu
    vram_mb: int
    use_tensorrt: bool
    trt_fp16: bool
    trt_int8: bool
    trt_int8_calibration_cache: Optional[str]
    trt_workspace_mb: int
    gpu_mem_limit_mb: int
    arena_extend_strategy: str  # kNextPowerOfTwo | kSameAsRequested
    concurrency: int  # max in-flight infer() calls this device accepts at once (our stand-in for "replicas")
    cuda_graph: bool = False


@dataclasses.dataclass
class ServerConfig:
    host: str = "0.0.0.0"
    port: int = 8443
    tls_cert: Optional[str] = None
    tls_key: Optional[str] = None
    api_key: Optional[str] = None
    models_dir: str = "models"
    manifest_path: str = "models_manifest.yaml"
    # Model ids to load at startup. "core" / "full" mirror the Android app's bundling sets (see catalog.py +
    # models_manifest.yaml groups); a list loads exactly those ids instead.
    model_set: str = "core"
    devices: List[DeviceConfig] = dataclasses.field(default_factory=list)
    trt_cache_dir: str = "trt_cache"
    log_level: str = "info"

    @property
    def uses_tls(self) -> bool:
        return bool(self.tls_cert and self.tls_key)


def load_config(path: Path = DEFAULT_CONFIG_PATH) -> ServerConfig:
    with open(path, "r") as f:
        raw = yaml.safe_load(f) or {}
    devices = [DeviceConfig(**d) for d in raw.get("devices", [])]
    if not devices:
        # No hardware plan on file (e.g. config written by hand): fall back to a single CPU device so the server
        # still starts, just without acceleration. Run setup_server.sh for a real plan.
        devices = [DeviceConfig(
            index=-1, name="CPU", tier="cpu", vram_mb=0, use_tensorrt=False, trt_fp16=False, trt_int8=False,
            trt_int8_calibration_cache=None, trt_workspace_mb=0, gpu_mem_limit_mb=0,
            arena_extend_strategy="kSameAsRequested", concurrency=max(1, (os.cpu_count() or 4) // 2),
        )]
    return ServerConfig(
        host=raw.get("host", "0.0.0.0"),
        port=int(raw.get("port", 8443)),
        tls_cert=raw.get("tls_cert"),
        tls_key=raw.get("tls_key"),
        api_key=raw.get("api_key"),
        models_dir=raw.get("models_dir", "models"),
        manifest_path=raw.get("manifest_path", "models_manifest.yaml"),
        model_set=raw.get("model_set", "core"),
        devices=devices,
        trt_cache_dir=raw.get("trt_cache_dir", "trt_cache"),
        log_level=raw.get("log_level", "info"),
    )


def save_config(cfg: ServerConfig, path: Path = DEFAULT_CONFIG_PATH) -> None:
    raw = {
        "host": cfg.host, "port": cfg.port, "tls_cert": cfg.tls_cert, "tls_key": cfg.tls_key, "api_key": cfg.api_key,
        "models_dir": cfg.models_dir, "manifest_path": cfg.manifest_path, "model_set": cfg.model_set,
        "trt_cache_dir": cfg.trt_cache_dir, "log_level": cfg.log_level,
        "devices": [dataclasses.asdict(d) for d in cfg.devices],
    }
    with open(path, "w") as f:
        yaml.safe_dump(raw, f, sort_keys=False)
